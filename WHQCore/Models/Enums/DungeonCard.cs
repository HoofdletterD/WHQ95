namespace WHQCore.Models.Enums;

/// <summary>
/// Represents a single Dungeon Card from Warhammer Quest.
/// </summary>
public record DungeonCard
{
    /// <summary>
    /// Name of the dungeon card.
    /// </summary>
    public string Name { get; init; } = string.Empty;

    /// <summary>
    /// Expansion or source set.
    /// </summary>
    public ExpansionSet Set { get; init; }

    /// <summary>
    /// Type of dungeon card.
    /// </summary>
    public DungeonCardType CardType { get; init; }

    /// <summary>
    /// Number of copies that exist in the physical deck.
    /// </summary>
    public int Quantity { get; init; }

    /// <summary>
    /// Card size description (Small, Medium, Large, etc.).
    /// </summary>
    public string Size { get; init; } = string.Empty;

    /// <summary>
    /// Number of board sections represented by the card.
    /// </summary>
    public int TileCount { get; init; }

    /// <summary>
    /// Additional doors beyond the normal passage entrance.
    /// </summary>
    public int AdditionalDoors { get; init; }

    /// <summary>
    /// Lore or flavour text.
    /// </summary>
    public string Lore { get; init; } = string.Empty;

    /// <summary>
    /// Special rules associated with the card.
    /// </summary>
    public string Rules { get; init; } = string.Empty;

    /// <summary>
    /// Whether this card creates a dungeon branch.
    /// Useful for T-Junctions and similar cards.
    /// </summary>
    public bool CreatesBranch => AdditionalDoors > 1;

    /// <summary>
    /// Total exits generated by this card.
    /// The entrance counts as one.
    /// </summary>
    public int TotalExits => AdditionalDoors + 1;

    public override string ToString()
    {
        return $"{Name} ({Set})";
    }
}

public enum DungeonCardType
{
    Corridor,
    DungeonRoom,
    ObjectiveRoom,
    Event,
    Special,
    Stairway,
    Entrance,
    Exit
}

public enum ExpansionSet
{
    CoreGame,
    CatacombsOfTerror,
    LairOfTheOrcLord,
    WhiteDwarf,
    FanMade,
    Custom,
    WD192,
    WD185,
    WD186,
    WD195,
    WD204
}
